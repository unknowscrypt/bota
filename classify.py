"""
Простая классификация вопроса по ключевым словам — выбирает, какая колода
подойдёт для расклада: классическое Таро Уэйта или более тёмное,
психологическое Таро Безумной Луны.

Это эвристика на ключевых словах (без обращения к внешним AI-сервисам) —
быстро работает и не требует API-ключей. При желании потом можно заменить
на вызов языковой модели для более точной классификации.
"""

LOVE_KEYWORDS = [
    "любов", "отношени", "парн", "девушк", "мужчин", "муж", "жену", "жена",
    "чувств", "влюб", "свида", "флирт", "пара", "расста", "измен", "брак",
    "свадьб", "ревну", "нравит", "симпати",
]

DEEP_KEYWORDS = [
    "страх", "боюсь", "судьб", "себя", "внутренн", "прошл", "тревог",
    "кризис", "депресс", "смысл", "потерял", "тьма", "почему я", "пустот",
    "одиноч", "вина", "стыд", "травм", "не понимаю себя", "теряю себя",
]


def classify_question(question: str) -> str:
    """Возвращает 'love', 'deep' или 'general'."""
    if not question:
        return "general"
    text = question.lower()
    if any(kw in text for kw in DEEP_KEYWORDS):
        return "deep"
    if any(kw in text for kw in LOVE_KEYWORDS):
        return "love"
    return "general"


def pick_deck(category: str) -> str:
    """Возвращает 'waite' или 'moon' в зависимости от темы вопроса."""
    if category == "deep":
        return "moon"
    return "waite"
