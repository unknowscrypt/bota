def _build_minor_arcana():
    deck = []
    emoji_map = {"wands": "🔥", "cups": "💧", "swords": "🗡️", "pentacles": "🪙"}
    for suit_key, suit in SUITS.items():
        for rank in RANKS:
            name = f"{rank['name']} {suit['name']}"
            upright = f"{rank['upright'].replace('сфере', suit['theme'])}."
            reversed_ = f"{rank['reversed'].replace('сфере', suit['theme'])}."
            deck.append({
                "id": f"{suit_key}_{rank['id']}",
                "name": name,
                "emoji": emoji_map[suit_key],
                "upright": upright[0].upper() + upright[1:],
                "reversed": reversed_[0].upper() + reversed_[1:],
            })
    return deck


MINOR_ARCANA = _build_minor_arcana()

