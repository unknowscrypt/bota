"""
Собирает карту дня в формат тёплого напутствия, а не сухой трактовки —
"сегодня у тебя будет хороший день, и вот почему" вместо голого значения карты.
"""

import random

OPENERS_UPRIGHT = [
    "Сегодня всё сложится удачно.",
    "Похоже, сегодня будет по-настоящему хороший день.",
    "День обещает быть лёгким и приятным.",
    "Сегодня многое получится само собой, без лишней борьбы.",
    "Настрой на сегодня хороший — можно немного расслабиться.",
    "Сегодня — один из тех дней, когда всё складывается вовремя.",
]

OPENERS_REVERSED = [
    "Сегодня может быть чуть шероховато с утра, но в целом день на твоей стороне.",
    "День начнётся не идеально, но выправится, если не форсировать события.",
    "Возможна лёгкая заминка — но она не определяет весь день.",
    "Сегодня стоит сбавить обороты, и тогда всё пройдёт мягче.",
    "День просит немного терпения в начале — дальше станет легче.",
]

CLOSERS = [
    "Позволь себе просто плыть по течению.",
    "Доверься моменту — не всё нужно контролировать.",
    "Маленькие радости сегодня решают больше, чем кажется.",
    "Ты справишься с тем, что будет, даже если пока не знаешь как.",
    "Не торопи события — сегодня как раз тот случай, когда время работает на тебя.",
    "Отнесись к себе сегодня чуть бережнее обычного.",
]


def build_daily_forecast(card_name: str, meaning: str, reversed_: bool) -> str:
    opener = random.choice(OPENERS_REVERSED if reversed_ else OPENERS_UPRIGHT)
    closer = random.choice(CLOSERS)
    snippet = meaning.split(".")[0].strip()
    if snippet:
        snippet = snippet[0].lower() + snippet[1:]
    bridge = f"Карта дня — «{card_name}»: {snippet}."
    return f"{opener} {bridge} {closer}"
